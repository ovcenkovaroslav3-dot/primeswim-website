/**
 * Веб-версия Прайми из исходного выреза.
 *
 * Источник — media-source/brand/praimi-breach-cutout-v2.png, 2048×2048 PNG с
 * альфой, около 4,4 МБ.
 *
 * ВТОРАЯ ВЕРСИЯ ОТЛИЧАЕТСЯ СПИННЫМ ПЛАВНИКОМ. У первой он был низкий и
 * заглаженный назад: на 200–300 пикселях, то есть в том размере, в каком
 * фигура и стоит на сайте, он сливался с пластом воды за ним, и силуэт
 * читался дельфином. Плавник — главный опознавательный признак косатки
 * после белых полей, и терять его на телефоне нельзя. Первая версия лежит
 * рядом с пометкой -archive. Класть такой файл в public нельзя: статическая сборка
 * не пересжимает картинки на лету, и посетитель качал бы архивный размер,
 * чтобы увидеть фигуру шириной в 400 пикселей.
 *
 * ЧТО ДЕЛАЕТ СКРИПТ:
 *   1. обрезает пустые поля по альфе — вокруг фигуры их около четверти кадра,
 *      и они стоили бы и веса, и точности позиционирования: элемент с
 *      невидимыми полями невозможно прижать к краю, не угадывая;
 *   2. пересчитывает под реальный размер показа;
 *   3. сохраняет WebP с альфой и AVIF рядом — так же, как устроены остальные
 *      картинки сайта (см. public/media/preview/README.md).
 *
 * ПОЧЕМУ ДВА РАЗМЕРА. Телефон показывает фигуру примерно в 200 CSS-пикселей,
 * десктоп — примерно в 480. Один файл под больший размер означал бы, что
 * телефон качает вчетверо больше нужного, а это как раз то устройство, где
 * канал уже и дороже.
 *
 * ЗАПУСК: node scripts/make-mascot-web.mjs
 */

import { mkdir } from 'node:fs/promises';
import { stat } from 'node:fs/promises';
import sharp from 'sharp';

const SRC = 'media-source/brand/praimi-breach-cutout-v2.png';

/*
  НЕ ЗЕРКАЛИМ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА.

  Сначала вырез отражали: в исходнике Прайми выходит из воды головой
  влево-вверх, и рассуждение было такое — на странице, которую читают слева
  направо, фигура, идущая назад, тормозит взгляд. Логично на словах и неверно
  на экране. Прайми стоит справа от заголовка, и, развёрнутая влево, она
  смотрит в текст, а не наружу: направление ведёт взгляд обратно к тому, ради
  чего экран собран. Отражённая — уводила за край.

  Второй довод в ту же сторону: ключевой свет в рендере идёт сверху слева,
  как и световые шахты в сцене воды под ней. Отражение разворачивало блики
  навстречу сцене.

  Флаг оставлен, чтобы решение было видно и обратимо одной строкой.
*/
const FLOP = false;
const OUT = 'public/media/mascot';

/*
  Ширины взяты замером, а не на глаз: фигура показывается в 194–226 CSS-пикселей
  на телефонах и в 303–358 на экранах от 768 (замер по всем брейкпоинтам).
  Двойная плотность плюс небольшой запас даёт 420 и 760.

  Первая версия стояла на 1000 для крупного файла — это почти трёхкратный
  запас, и он был не бесплатным: у позы «прорыв» вокруг тела висят тонкие
  пласты воды, которые сжимаются плохо, и лишняя ширина стоила вдвое больше
  байт, чем у прежней спокойной позы.
*/
const SIZES = [
  { name: 'orca-3d-sm', width: 420 },
  { name: 'orca-3d', width: 760 },
];

await mkdir(OUT, { recursive: true });

/*
  trim по альфе: sharp считает границу по непрозрачным пикселям, если явно
  задать прозрачный фон. Порог 8 — мягкая кромка рендера не режется вместе
  с полем, но и полупрозрачный мусор по краям не удерживает рамку.
*/
const source = sharp(SRC);
const trimmed = await (FLOP ? source.flop() : source)
  .trim({ background: { r: 0, g: 0, b: 0, alpha: 0 }, threshold: 8 })
  .toBuffer({ resolveWithObject: true });

console.log(
  `обрезано до ${trimmed.info.width}×${trimmed.info.height} (было 2048×2048)`,
);

for (const { name, width } of SIZES) {
  const base = sharp(trimmed.data).resize({ width, withoutEnlargement: true });

  await base.clone().webp({ quality: 86, alphaQuality: 90, effort: 6 }).toFile(`${OUT}/${name}.webp`);
  await base.clone().avif({ quality: 62, effort: 6 }).toFile(`${OUT}/${name}.avif`);

  const w = (await stat(`${OUT}/${name}.webp`)).size / 1024;
  const a = (await stat(`${OUT}/${name}.avif`)).size / 1024;
  console.log(`${name}: webp ${w.toFixed(0)} KB, avif ${a.toFixed(0)} KB`);
}

/*
  ОТДЕЛЬНАЯ МАСКА ДЛЯ БЛИКА — ПОТОМУ ЧТО ПЕРЕИСПОЛЬЗОВАТЬ ГОТОВЫЙ ФАЙЛ НЕЛЬЗЯ.

  Блик по кромке (`.praimi-shine`) маскируется формой фигуры, и сначала маской
  служил сам талисман в WebP — с расчётом, что телефон уже скачал этот файл и
  возьмёт его из кеша. Расчёт держался ровно до тех пор, пока рядом не лёг
  AVIF: <picture> стал отдавать телефону `orca-3d-sm.avif`, а маска по-прежнему
  просила `.webp`. Сетевой замер показал оба файла — 21 KB плюс 38 KB, второй
  целиком ради формы.

  Подставить в маску AVIF нельзя: у `mask-image` нет согласования форматов, а
  если файл не поймут, свойство считается пустым — и градиент ляжет прямоугольником
  поверх фигуры. Это хуже, чем отсутствие блика.

  Поэтому маска своя: только альфа, белым по прозрачному, PNG — формат,
  который понимают все. Разрешения ей нужно немного: она растягивается под
  элемент и держит форму, а не детали. 240 px против 420 у самой фигуры — это
  9 KB вместо 38.
*/
const MASK_WIDTH = 240;
const maskShape = sharp(trimmed.data).resize({ width: MASK_WIDTH });
const maskAlpha = await maskShape.clone().extractChannel('alpha').toBuffer();
const maskMeta = await maskShape.clone().toBuffer({ resolveWithObject: true });

await sharp({
  create: {
    width: maskMeta.info.width,
    height: maskMeta.info.height,
    channels: 3,
    background: '#ffffff',
  },
})
  .joinChannel(maskAlpha)
  .png({ compressionLevel: 9, palette: true })
  .toFile(`${OUT}/orca-3d-mask.png`);

console.log(
  `orca-3d-mask.png: ${((await stat(`${OUT}/orca-3d-mask.png`)).size / 1024).toFixed(0)} KB (маска блика)`,
);

/*
  Размеры готового файла нужны разметке: без width/height браузер не знает
  пропорций до загрузки и двигает соседей, когда картинка приходит. Печатаем
  их здесь, чтобы не подглядывать в файл руками.
*/
const meta = await sharp(`${OUT}/orca-3d.webp`).metadata();
console.log(`\nдля content/media.ts: width: ${meta.width}, height: ${meta.height}`);
