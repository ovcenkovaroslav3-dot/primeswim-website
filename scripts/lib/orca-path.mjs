/** Грудной плавник: лопасть, уходящая назад-вниз. */
export const PECT = 'M196 118c-10 12-26 34-38 46-4 4-10 2-9-4 3-18 11-34 19-42Z';

/** Брюшное поле: от подбородка вдоль низа и вверх на бок за плавником. */
