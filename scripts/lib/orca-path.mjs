/** Рамка, в которой нарисован знак. */
export const VIEW_BOX = { width: 264, height: 176 };

/**
 * Разметка знака одной строкой.
 *
 * @param body   цвет тела
 * @param field  цвет брюшного поля и заглазничного пятна; если не задан,
 *               знак выходит сплошным силуэтом — так он нужен там, где
 *               двухцветность не читается (мелкий размер, вышивка, плоттер)
 * @param tilt   наклон в градусах: 0 — знак в покое, −16 — в движении
 */
export function orcaMarkup({ body, field = null, tilt = 0 } = {}) {
  const inner = [
    `<g fill="${body}"><path d="${BODY}"/><path d="${PECT}"/></g>`,
    field
      ? `<g fill="${field}"><path d="${BELLY}"/>` +
        `<ellipse cx="212" cy="74" rx="15.5" ry="7" transform="rotate(-15 212 74)"/></g>`
      : '',
  ].join('');

  return tilt ? `<g transform="rotate(${tilt} 132 88)">${inner}</g>` : inner;
}
