'use client';

import { usePathname } from 'next/navigation';
import { useEffect } from 'react';

/**
 * Один наблюдатель на весь документ.
 *
 * Секции остаются серверными компонентами: чтобы элемент проявился, ему
 * достаточно класса `reveal` или `reveal-mask` — клиентская обёртка вокруг
 * каждой секции не нужна, и лишний JavaScript в браузер не уезжает.
 *
 * Элементы наблюдаются один раз: после появления наблюдение снимается,
 * поэтому при обратной прокрутке контент не мигает.
 *
 * Скрытие включается отсюда: атрибут data-reveal="on" на <html> ставится
 * только когда этот эффект действительно выполнился. Без него правила в
 * globals.css не применяются и весь контент виден. Это защита от главной
 * беды такой схемы — один сбой оставлял блок прозрачным навсегда, и на
 * светлой секции получался белый прямоугольник вместо карточки.
 *
 * ПЕРЕЗАПУСК ПРИ СМЕНЕ МАРШРУТА. ScrollReveal живёт в корневом layout, а
 * layout при переходе между страницами (клиентская навигация Next.js, без
 * перезагрузки) не размонтируется — размонтируется и монтируется заново
 * только `children`. С пустым списком зависимостей эффект выполнялся бы
 * ровно один раз за всю сессию: он находил `.reveal`-элементы только той
 * страницы, что была открыта первой, а любая страница, на которую перешли
 * кликом по ссылке, оставалась ненаблюдаемой — CSS уже прятал её контент
 * (data-reveal="on" стоит на <html> с первой же страницы), а добавить
 * is-in было некому. Так вся секция превращалась в белый экран: не один
 * блок, а страница целиком, но только при переходе по ссылке — при прямой
 * загрузке того же адреса эффект отрабатывал как надо. usePathname меняет
 * значение при каждой смене маршрута и перезапускает эффект: он находит
 * уже вставленные в DOM `.reveal`-элементы новой страницы (эффекты
 * выполняются после коммита, так что к этому моменту они точно на месте)
 * и берёт их под наблюдение заново.
 *
 * ВАЖНО для клиентских компонентов. Класс `is-in` дописывается прямо в DOM,
 * мимо React. Если тот же элемент получает className, собранный из состояния,
 * то при первой же перерисовке React перезапишет атрибут целиком и погасит
 * элемент навсегда — наблюдение к тому моменту уже снято. Так пропадала вся
 * правая колонка в «Что происходит в эти 45 минут». Поэтому на элементе с
 * `reveal` строка класса должна быть постоянной, а переменные состояния —
 * жить в data-атрибутах.
 */
export function ScrollReveal() {
  const pathname = usePathname();

  useEffect(() => {
    const root = document.documentElement;
    const targets = document.querySelectorAll<HTMLElement>(
      '.reveal, .reveal-mask',
    );

    const reduced = window.matchMedia(
      '(prefers-reduced-motion: reduce)',
    ).matches;

    // при отключённой анимации прятать нечего: атрибут не ставим вовсе,
    // и правила скрытия в CSS так и не включаются
    if (reduced) return;

    /*
      Порядок важен. Сначала включаем скрытие, следом — тем же синхронным
      куском кода — показываем то, что уже в кадре. Браузер рисует только
      после выхода из эффекта, поэтому промежуточное состояние на экран не
      попадает и первый экран не моргает.
    */
    root.dataset.reveal = 'on';

    const io = new IntersectionObserver(
      (entries) => {
        entries.forEach((e) => {
          if (!e.isIntersecting) return;
          e.target.classList.add('is-in');
          io.unobserve(e.target);
        });
      },
      /*
        threshold: 0 — реагируем на любой видимый пиксель. Прежние 0.05
        требовали, чтобы в кадр попало 5% площади блока, а блоки тут бывают
        выше экрана: у «Как проходит первое занятие» это 797 px при рабочей
        высоте окна 715 px. Запас был, но небольшой, и держался на том, что
        rootMargin не съест лишнего. Нулевой порог убирает этот расчёт совсем.
      */
      { rootMargin: '0px 0px -12% 0px', threshold: 0 },
    );

    targets.forEach((el) => {
      // то, что уже видно при загрузке, показываем без задержки на наблюдение
      const r = el.getBoundingClientRect();
      if (r.top < window.innerHeight) el.classList.add('is-in');
      else io.observe(el);
    });

    return () => io.disconnect();
  }, [pathname]);

  return null;
}
