import imageLoader from '@/lib/image-loader';

/*
  Прайми — талисман PRIME SWIM, объёмная косатка.

  Имя дал владелец 13 сентября 2026. Латиницей — PRIMI, по логике самого
  бренда (PRIME → PRIMI), а не транслитерацией: в подписях к Reels, на
  наклейках и на мерче имя должно читаться как часть названия школы.

  ПОЗА — «ПРОРЫВ», и выбрал её владелец из трёх концепций (ливрея, след,
  прорыв — все три лежат в media-source/brand/concepts/). Прайми выходит из
  воды на пике силы: тело выгнуто, голова и грудь уже высоко, хвост ещё внизу,
  с задней кромки срываются пласты воды. На первом экране это работает
  буквально — она выпрыгивает из кадра бассейна, который лежит под ней.

  ЧЕМ ЭТА ОТЛИЧАЕТСЯ ОТ ПРЕЖНЕЙ. Прежняя была мультяшным персонажем: огромные
  блестящие глаза, улыбка, шапочка, нарисованный всплеск. Она называла возраст
  — «кружок для малышей» — там, где школа готовит разряды, и подросток читал её
  как «сюда я не хожу». Эта — та же косатка по смыслу и другая по регистру:
  скульптурная форма без лица, фирменный фиолетовый, одна лаймовая кромка по
  передней кромке плавника. Ребёнку восьми лет она интересна как настоящая
  косатка, подростку — как знак спортивного бренда.

  РИСОВАЛАСЬ ЧЕРЕЗ HIGGSFIELD, промты и правила — в docs/brand-prime-orca.md.
  Плоский векторный знак (OrcaMark.tsx) при этом остаётся и не заменяется:
  на 20 пикселях — в фавиконе, в шапке, в подвале — объёмный рендер
  превращается в пятно, а вектор читается. Разделение простое: **вектор для
  знаков, рендер для присутствия**.

  ПОЧЕМУ ОНА НЕ ЗАНИМАЕТ МЕСТА В ПОТОКЕ. Прежняя стояла отдельным блоком и
  съедала на телефоне 520 px между кнопкой записи и первым доказательством —
  полэкрана декорации ровно там, где родитель решает, читать дальше или
  закрыть. Эта лежит абсолютом поверх кадра: presence есть, высоты нет.

  ДВА ФАЙЛА, А НЕ ОДИН. Замер по всем брейкпоинтам: телефон показывает фигуру
  в 194–226 CSS-пикселей, экраны от 768 — в 303–358. Один файл под больший
  размер означал бы, что телефон качает вчетверо лишнего, а это ровно то
  устройство, где канал дороже. Разделение по `media` в <source>, а не через
  srcset по ширине: ширина показа задана раскладкой, а не вьюпортом, и
  браузеру её не угадать.

  AVIF первым, WebP запасным: браузер берёт первый формат, который понимает.
  Собирается всё одной командой — node scripts/make-mascot-web.mjs.
*/
export function MascotOrca({ className = '' }: { className?: string }) {
  const src = (name: string) => imageLoader({ src: `/media/mascot/${name}` });
  const maskSrc = src('orca-3d-sm.webp');

  return (
    /*
      Обёртка отвечает за посадку, внутренний слой — за движение. Разделение
      нужно, чтобы анимация не спорила с позиционированием: у обёртки свои
      absolute-координаты, у ребёнка только transform.
    */
    <div className={`pointer-events-none ${className}`.trim()}>
      <div className="praimi-hover relative">
        <picture className="block">
          <source
            type="image/avif"
            media="(min-width: 768px)"
            srcSet={src('orca-3d.avif')}
          />
          <source type="image/avif" srcSet={src('orca-3d-sm.avif')} />
          <source
            type="image/webp"
            media="(min-width: 768px)"
            srcSet={src('orca-3d.webp')}
          />
          {/*
            Фигура декоративная: смысл первого экрана несут заголовок, факты и
            фотография площадки, а не она. Пустой alt убирает её из чтения с
            экрана — иначе программа объявляла бы картинку, за которой нет
            сведений, которых нет в тексте рядом.
          */}
          <img
            src={src('orca-3d-sm.webp')}
            alt=""
            aria-hidden="true"
            width={760}
            height={760}
            decoding="async"
            /*
              Не priority. Кандидат в LCP на первом экране — фотография
              бассейна, и очередь загрузки принадлежит ей: талисман, вставший
              в неё первым, отодвинул бы единственное доказательство места
              ради украшения.
            */
            fetchPriority="low"
            className="block h-auto w-full select-none"
          />
        </picture>

        {/*
          Блик по кромке. Маской служит сам файл талисмана, поэтому светлая
          полоса видна только там, где у картинки непрозрачные пиксели, —
          свет идёт по фигуре, а не по прямоугольнику вокруг неё.

          Маска берётся маленькая: ей нужна форма, а не разрешение, и грузить
          ради неё второй файл в полный размер незачем. На телефоне это тот же
          файл, что и сам талисман, — браузер возьмёт его из кеша.
        */}
        <span
          aria-hidden="true"
          className="praimi-shine"
          style={{
            maskImage: `url(${maskSrc})`,
            WebkitMaskImage: `url(${maskSrc})`,
          }}
        />
      </div>
    </div>
  );
}
