import { proofPoints } from '@/content/method';

/*
  Полоса доказательств — первое, что идёт после первого экрана.

  Родитель только что прочитал обещание. Дальше он либо получает основания
  ему верить, либо уходит. Раньше на этом месте начиналась большая секция
  «Почему мы» с рассуждением про технику: аргумент верный, но он требует
  чтения, а здесь нужна проверяемая конкретика за один взгляд.

  Секция намеренно низкая — это полоса, а не блок. Ни заголовка, ни
  подводки: каждый пункт сам себе утверждение, а лишний заголовок отодвинул
  бы вниз всё, что за ним.

  Тёмная, потому что стоит вплотную к первому экрану и дочитывает его —
  светлая полоса здесь резала бы страницу пополам сразу после hero.

  Утверждения набраны белым, а не лаймом. Полоса стоит в том же экране,
  что и кнопка записи, и четыре лаймовых строки спорили с ней за роль
  главного пятна: на первом развороте лайма было девять штук — логотип,
  кнопка в шапке, cookie, надзаголовок, слово в заголовке, кнопка, и вот
  эти четыре. Лайм остался кнопке.

  УТВЕРЖДЕНИЕ В ОДНУ СТРОКУ, А НЕ ЦИФРА С ПОДПИСЬЮ. Написанное выше про
  «полосу, а не блок» верно по замыслу и не было верно по разметке: пункты
  стояли двухъярусно — крупное значение, под ним приглушённая подпись, —
  то есть ровно тем же приёмом, каким набрана стеклянная карточка фактов
  на первом экране. А она стоит в 110 пикселях выше, в том же тёмном
  экране: два четырёхколоночных грида подряд, одинаковые по форме и по
  фону. Второй читался продолжением первого и пропускался глазом — то
  есть полоса, которой отведено «дочитать первый экран», не читалась.

  Форма была неверна и сама по себе. Цифра с подписью — приём для чисел,
  и у Hero там числа: 850 ₽, 45 минут, до 12, 13 лет. Здесь чисел нет,
  кроме первого пункта: «Четыре стиля», «КМС по плаванию», «Старты и
  разряды» — это фразы, наряженные в статистику.

  Теперь пункт — одна строка: утверждение белым, уточнение через тире
  приглушённым. Разделители вертикальные на десктопе и горизонтальные на
  телефоне: они и делают из блока полосу.

  Цена замерена: 130 → 142 px на десктопе (последний пункт длиннее прочих
  и переносится в три строки, по нему и встаёт высота ряда) и 225 → 298 на
  телефоне — четыре строки вместо двух колонок. На телефоне это дороже
  всего, и это осознанно: в две колонки утверждение такой длины ломается
  на пять строк по 20 символов, то есть перестаёт читаться за один взгляд,
  ради чего полоса и стоит.
*/
export function ProofStrip() {
  return (
    <section
      aria-label="Коротко о школе"
      className="on-dark bg-abyss-900 px-4 py-8 text-white sm:px-6 sm:py-10"
    >
      <ul className="mx-auto grid w-full max-w-6xl gap-y-4 lg:grid-cols-4 lg:gap-y-0">
        {proofPoints.map((point, i) => (
          <li
            key={point.id}
            /*
              Разделитель рисует сам пункт, а не divide-* на сетке: при
              переходе с одной колонки на четыре у divide-x граница легла бы
              не туда, где её ждёшь, — утилита считает по порядку в разметке,
              а не по тому, где элемент оказался в сетке.
            */
            className={`reveal text-sm leading-snug sm:text-[15px] lg:pr-6 ${
              i > 0
                ? 'border-t border-white/15 pt-4 lg:border-t-0 lg:border-l lg:pt-0 lg:pl-6'
                : ''
            }`}
            style={{ ['--reveal-delay' as string]: `${i * 70}ms` }}
          >
            <span className="font-medium text-white">{point.value}</span>
            <span className="text-white/55"> — {point.label}</span>
          </li>
        ))}
      </ul>
    </section>
  );
}
