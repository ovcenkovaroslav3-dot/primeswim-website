/*
  Знак PRIME SWIM — плоский силуэт Прайми.

  Прайми — косатка, талисман школы; объёмный её рендер живёт в
  MascotOrca.tsx и стоит ровно в одном месте, на первом экране. Здесь —
  тот же персонаж, сведённый до силуэта: рендер для присутствия, вектор
  для знаков. Разбор — в docs/brand-prime-orca.md.

  ЭТО НЕ ПЕРСОНАЖ, А ЗНАК. Разница принципиальная и она же причина, по которой
  прежний талисман — трёхмерная улыбающаяся косатка в шапочке — ушёл с первого
  экрана. У персонажа есть лицо, настроение и возраст: та иллюстрация говорила
  «кружок для малышей», и подросток 15–17 лет, ради которого существуют старты
  и разряды, читал её как сообщение «ты сюда не ходишь». Знак возраста не
  называет — он называет вид спорта.

  Файл иллюстрации остался в public/media/mascot/orca-v1.webp: если решение
  когда-нибудь пересмотрят, возвращать нечего — достаточно вернуть компонент.

  ЧТО ДЕЛАЕТ КОСАТКУ КОСАТКОЙ. Силуэт сам по себе не отличается от дельфина
  или акулы — проверено на чёрной заливке, читается «рыба». Опознаётся она по
  двум белым пятнам: заглазничному (овал за глазом) и брюшному, которое
  поднимается на бок за грудным плавником. Поэтому знак двухцветный, а не
  монолитный, и оба пятна выживают вплоть до 20 px — на этом размере от
  фигуры остаётся ровно то, что нужно: тёмное тело, белая полоса снизу,
  светлая точка у головы.

  ГЕОМЕТРИЯ взята от реальных пропорций, а не от стилизации. Длина от рострума
  до выемки хвоста принята за 100 условных единиц:
    • спинной плавник — основание на 46–60, высота 18 (самец, высокий);
    • грудной — от 68 до 78, уходит назад-вниз;
    • наибольшая толщина тела — на 50–62, перед плавником;
    • заглазничное пятно — 74–90, наклон -15°.
  Отсюда и viewBox: x = 12 + 2.4·u, y = 88 − 2.4·v.

  ОДИН ПУТЬ НА ТЕЛО И ОДИН НА ПЛАВНИК — никаких обводок. Знак должен одинаково
  печататься на футболке, резаться плоттером для наклейки и ложиться в фавикон.
  Обводка на всех трёх носителях ведёт себя по-разному, заливка — одинаково.
*/

/** Тело: рострум → лоб → спинной плавник → спина → хвост → брюхо → подбородок. */
const BODY =
  'M252 90C244 72 236 62 223 58c-11-4-23-5-33-4-14 1-24 0-32-2L134 9c-2-5-10-4-10 2l-2 41c-18 3-26 5-38 8-16 4-34 9-48 15L8 56c-5-3-9 2-6 7l15 25-15 25c-3 5 1 10 6 7l28-19c14 7 30 15 48 20 20 6 34 8 48 9 18 1 30-1 43-5 15-4 25-7 37-14 20-11 36-15 40-21Z';

/** Грудной плавник: лопасть, уходящая назад-вниз. */
const PECT = 'M196 118c-10 12-26 34-38 46-4 4-10 2-9-4 3-18 11-34 19-42Z';

/**
 * Брюшное поле. Идёт от подбородка вдоль низа и поднимается на бок за
 * грудным плавником — тот самый «крюк», по которому косатку узнают сбоку.
 */
const BELLY =
  'M252 90c-8 10-24 18-40 22-16 5-36 11-54 14-18 3-38 4-54 1-8-2-14-4-20-6v-13c10 3 24 5 38 5 18 0 38-3 56-8 24-7 62-21 74-29Z';

type Tone = 'brand' | 'white' | 'ink' | 'currentColor';

/**
 * @param tone  brand — фиолетовое тело с белыми полями (основной вариант);
 *              white — сплошной белый силуэт для тёмных плашек;
 *              ink   — то же чернилами для светлых;
 *              currentColor — наследует цвет текста, для строчных маркеров.
 * @param tilt  наклон в градусах. Ноль — знак в покое (фавикон, подвал),
 *              -16 — в движении: так он идёт вверх, а не плывёт ровно.
 */
export function OrcaMark({
  tone = 'brand',
  tilt = 0,
  className = '',
  title,
}: {
  tone?: Tone;
  tilt?: number;
  className?: string;
  title?: string;
}) {
  const solid = tone !== 'brand';
  const bodyFill =
    tone === 'brand'
      ? 'var(--color-brand-600)'
      : tone === 'white'
        ? '#ffffff'
        : tone === 'ink'
          ? 'var(--color-ink)'
          : 'currentColor';

  /*
    Наклон делается запасом вокруг viewBox, а не обрезкой: повёрнутая фигура
    выходит за исходную рамку углами хвоста и плавника, и без запаса они
    срезались бы ровной линией.
  */
  const pad = tilt ? 26 : 0;
  const view = `${-pad} ${-pad} ${264 + pad * 2} ${176 + pad * 2}`;

  return (
    <svg
      viewBox={view}
      fill="none"
      role={title ? 'img' : 'presentation'}
      aria-hidden={title ? undefined : 'true'}
      aria-label={title}
      focusable="false"
      className={className}
    >
      <g transform={tilt ? `rotate(${tilt} 132 88)` : undefined}>
        <g fill={bodyFill}>
          <path d={BODY} />
          <path d={PECT} />
        </g>
        {solid ? null : (
          <g fill="#ffffff">
            <path d={BELLY} />
            <ellipse
              cx="212"
              cy="74"
              rx="15.5"
              ry="7"
              transform="rotate(-15 212 74)"
            />
          </g>
        )}
      </g>
    </svg>
  );
}
