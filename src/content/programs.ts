/**
 * Направления занятий и преимущества школы.
 * Источник: primeswim.ru (блоки «Тренировки в воде с результатом», FAQ, раздел тренера).
 */

export type Program = {
  id: string;
  title: string;
  description: string;
  /** Кому подходит */
  audience: string;
  /**
   * Порядок, в котором идут первые занятия.
   *
   * Есть только у «с нуля»: остальные два направления начинаются не с
   * пустого места, и никакой последовательности «сначала это, потом то»
   * у них нет — там разбор техники и подготовка к стартам, а это не
   * ступени, а работа по кругу.
   *
   * Раньше эти четыре шага лежали внутри description одной строкой через
   * запятую. Родитель, который выбирает «с нуля», спрашивает как раз
   * «а что там будет на первом занятии» — списком это отвечает, прозой нет.
   */
  steps?: string[];
  /**
   * Страница, где направление разобрано подробно, если такая есть.
   * Нужна не всем: «с нуля» и «техника» целиком описаны здесь же, а
   * спортивное направление — это старты, сборы и разряды, и про них есть
   * отдельная страница. Без этой ссылки с главной на /sorevnovaniya/ не
   * вело ничего, кроме подвала.
   */
  href?: string;
};

