/**
 * Расписание занятий. Источник: primeswim.ru (раздел «Расписание занятий»).
 * Чтобы изменить расписание — отредактируйте массив ниже.
 */

export type ScheduleSlot = {
  id: string;
  day: string;
  /** Двухбуквенное сокращение для полосы недели */
  short: string;
  /**
   * Время начала каждой группы в этот день. В будни групп две подряд,
   * поэтому здесь список: одно значение на день сообщало бы родителю,
   * что тренировка одна, и вторую группу никто бы не увидел.
   */
  times: string[];
  /**
   * Короткое пояснение к слоту.
   *
   * В будни здесь важно слово «подряд». Без него «19:00 19:45» рядом с
   * подписью «две вечерние группы» читается двояко: и как одна тренировка
   * с 19:00 до 19:45, и как две группы, идущие одновременно. Проверено на
   * человеке со стороны — прочитал именно так, оба раза мимо.
   */
  note: string;
};

/**
 * Полная неделя в порядке дней. Нужна, чтобы показать не только дни
 * с занятиями, но и промежутки между ними: родителю важно видеть ритм
 * недели целиком, а не четыре карточки вразнобой.
 */
