/**
 * Текст согласия на обработку персональных данных.
 *
 * Отдельный документ, а не строчка под кнопкой. Политика описывает, что
 * Оператор делает с данными вообще; согласие — то, на что конкретно
 * соглашается человек, отправляя форму. Часть 4 статьи 9 152-ФЗ требует,
 * чтобы согласие было конкретным, предметным, информированным и
 * сознательным: человек должен видеть перечень данных, цель, срок и то,
 * кому данные уйдут.
 *
 * Состав данных описан по фактическому поведению формы — см.
 * src/lib/lead-schema.ts (поля) и server/lead/message.ts (что уходит в
 * сообщении вместе с заявкой). Если форма изменится, этот документ
 * придётся править в тот же коммит: расхождение между обещанным и
 * происходящим — это и есть нарушение, а не формальность.
 *
 * [ТРЕБУЕТ ПРОВЕРКИ ЮРИСТОМ] Формулировки. Фактическая часть проверена по
 * коду, правовая — нет.
 */

