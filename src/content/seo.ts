/**
 * Полный адрес страницы со слешем на конце — сборка настроена на
 * trailingSlash, и без него og:url расходился бы с canonical.
 */
export function pageUrl(page: PageSeo): string {
  return page.path === '/' ? `${site.url}/` : `${site.url}${page.path}/`;
}

/**
 * Метаданные внутренней страницы одним вызовом.
 *
 * Появилось потому, что раньше страницы задавали только title, description и
 * canonical, а блок openGraph наследовался из layout.tsx как есть. В итоге
 * все восемь внутренних страниц отдавали в og:title и og:url главную: ссылка
 * на расписание, отправленная в мессенджер, показывалась как ссылка на
 * главную. Теперь og собирается из тех же полей, что и сам заголовок.
 *
 * canonical передаётся без хвостового слеша — Next дописывает его сам,
 * потому что включён trailingSlash.
 */
export function pageMetadata(page: PageSeo): Metadata {
  const fullTitle = `${page.title} — ${site.name}`;

  return {
    title: page.title,
    description: page.description,
    alternates: { canonical: page.path },
    openGraph: {
      type: 'website',
      locale: 'ru_RU',
      siteName: site.name,
      title: fullTitle,
      description: page.description,
      url: pageUrl(page),
      images: [ogImage],
    },
  };
}
