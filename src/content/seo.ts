/*
  Цены и расписание в описаниях собираются из тех же файлов, что и сами
  страницы. Иначе описание пришлось бы править вторым заходом, и рано или
  поздно поиск показывал бы цену, которой уже нет.
*/
/*
  Цены в описании набираются так же, как на самой странице: с разрядом
  через пробел. Без этого в выдаче стояло «1100 ₽», а на странице —
  «1 100 ₽», и сниппет выглядел набранным другой рукой.
*/
const money = (value: number | undefined) =>
  value === undefined ? '' : value.toLocaleString('ru-RU');
const trialPrice = money(prices.find((price) => price.id === 'trial')?.amount);
/*
  Стаж берётся из карточки тренера по той же причине, что и цены: число,
  вписанное в описание руками, однажды разойдётся с тем, что написано на
  самой странице, и поиск будет показывать устаревшее.
*/
